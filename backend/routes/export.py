"""
파일 내보내기 라우터
====================
생성된 코드를 ZIP 파일로 압축하여 다운로드합니다.
배포에 필요한 scaffolding 파일도 자동 포함합니다.
"""

import io
import json
import zipfile

from fastapi import APIRouter
from fastapi.responses import StreamingResponse
from pydantic import BaseModel

router = APIRouter(prefix="/api", tags=["export"])


class ExportFile(BaseModel):
    path: str
    code: str
    language: str = "tsx"


class ExportRequest(BaseModel):
    project_name: str = "my-project"
    files: list[ExportFile]


# ──────────────────────────────────────────────
# 배포용 Scaffolding 파일 생성
# ──────────────────────────────────────────────
def _make_package_json(name: str, has_backend: bool) -> str:
    pkg = {
        "name": name,
        "version": "1.0.0",
        "private": True,
        "scripts": {
            "dev": "next dev",
            "build": "next build",
            "start": "next start",
            "lint": "next lint",
        },
        "dependencies": {
            "next": "^14.2.0",
            "react": "^18.3.0",
            "react-dom": "^18.3.0",
        },
        "devDependencies": {
            "@types/node": "^20",
            "@types/react": "^18",
            "@types/react-dom": "^18",
            "typescript": "^5",
            "tailwindcss": "^3.4.0",
            "postcss": "^8",
            "autoprefixer": "^10",
        },
    }
    return json.dumps(pkg, indent=2, ensure_ascii=False)



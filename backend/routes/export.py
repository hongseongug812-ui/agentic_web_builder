@router.post("/export/zip")
async def export_zip(request: ExportRequest):
    """생성된 코드를 배포 가능한 프로젝트 ZIP으로 내보내기"""
    zip_buffer = io.BytesIO()
    name = request.project_name

    # 백엔드 파일이 있는지 체크
    has_backend = any(
        f.language in ("python", "py") or f.path.endswith(".py")
        for f in request.files
    )

    # 이미 포함된 파일 경로 목록
    existing_paths = {f.path for f in request.files}

    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        # 생성된 코드 파일
        for f in request.files:
            zf.writestr(f.path, f.code)

        # ── Scaffolding 파일 자동 추가 (없는 경우만) ──
        scaffolds = {
            "package.json": _make_package_json(name, has_backend),
            "tsconfig.json": TSCONFIG,
            "next.config.js": NEXT_CONFIG,
            "tailwind.config.js": TAILWIND_CONFIG,
            "postcss.config.js": POSTCSS_CONFIG,
            ".gitignore": GITIGNORE,
            "vercel.json": VERCEL_JSON,
            ".env.example": ENV_EXAMPLE,
            "Dockerfile": DOCKERFILE,
        }

        # globals.css가 없으면 추가
        if "src/app/globals.css" not in existing_paths:
            scaffolds["src/app/globals.css"] = GLOBAL_CSS

        # layout.tsx가 없으면 추가
        if "src/app/layout.tsx" not in existing_paths:
            scaffolds["src/app/layout.tsx"] = LAYOUT_TSX.replace("%PROJECT_NAME%", name)

        for path, content in scaffolds.items():
            if path not in existing_paths:
                zf.writestr(path, content)

        # README 자동 생성
        readme = f"# {name}\n\n"
        readme += "> 이 프로젝트는 **Agentic Web Builder**에 의해 자동 생성되었습니다.\n\n"
        readme += "## 시작하기\n\n"
        readme += "```bash\n"
        readme += "npm install\n"
        readme += "npm run dev\n"
        readme += "```\n\n"
        readme += "브라우저에서 [http://localhost:3000](http://localhost:3000)으로 접속하세요.\n\n"
        readme += "## Vercel 배포\n\n"
        readme += "```bash\n"
        readme += "npx vercel\n"
        readme += "```\n\n"
        readme += "## 파일 구조\n\n"
        readme += "| 파일 | 언어 |\n"
        readme += "|------|------|\n"
        for f in request.files:
            readme += f"| `{f.path}` | {f.language} |\n"
        readme += "\n## 기술 스택\n\n"
        readme += "- **Next.js 14** — React 풀스택 프레임워크\n"
        readme += "- **Tailwind CSS 3** — 유틸리티 CSS\n"
        readme += "- **TypeScript** — 타입 안전성\n"
        if has_backend:
            readme += "- **Python/FastAPI** — 백엔드 API\n"

        zf.writestr("README.md", readme)

    zip_buffer.seek(0)

    return StreamingResponse(
        zip_buffer,
        media_type="application/zip",
        headers={
            "Content-Disposition": f"attachment; filename={name}.zip",
        },
    )
